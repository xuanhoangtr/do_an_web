package com.utewedding.app.dto.request;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Digits;
import java.math.BigDecimal;
import java.util.UUID;

/** Admin-only command for the shop catalog. */
public class AdminProductForm {

    @NotNull(message = "Danh mục là bắt buộc.")
    @Positive(message = "Mã danh mục phải là số dương.")
    private Long categoryId;

    @NotBlank(message = "Tên sản phẩm không được để trống.")
    @Size(max = 120, message = "Tên sản phẩm tối đa 120 ký tự.")
    private String name;

    @Min(value = 0, message = "Giá không được âm.")
    private long unitPrice;

    @Min(value = 0, message = "Tồn kho không được âm.")
    private int stockQuantity;

    @Min(value = 0, message = "Mức giảm giá không được âm.")
    @Max(value = 100, message = "Mức giảm giá tối đa 100%.")
    private int discountPercent;

    @Size(max = 4000, message = "Mô tả tối đa 4000 ký tự.")
    private String description;

    @Size(max = 160, message = "Chất liệu tối đa 160 ký tự.")
    private String material;

    @Size(max = 2048, message = "URL hình ảnh tối đa 2048 ký tự.")
    private String imageUrl;

    private UUID managedMediaId;

    @Size(max = 80, message = "SKU tối đa 80 ký tự.")
    private String sku;

    private boolean skuAutoGenerated;

    @Size(max = 500, message = "Mô tả ngắn tối đa 500 ký tự.")
    private String shortDescription;

    @Size(max = 2000, message = "Hướng dẫn tùy chỉnh tối đa 2000 ký tự.")
    private String customizationGuide;

    @DecimalMin(value = "0.00", message = "Giá gốc trước giảm không được âm.")
    @Digits(integer = 17, fraction = 2, message = "Giá gốc trước giảm tối đa 17 chữ số nguyên và 2 chữ số thập phân.")
    private BigDecimal compareAtPrice;

    @jakarta.validation.constraints.Min(value = 1, message = "Số lượng tối thiểu phải từ 1 trở lên.")
    private int minOrderQuantity = 1;

    @PositiveOrZero(message = "Khối lượng không được âm.")
    private Integer weightGrams;

    @Size(max = 160, message = "Kích thước tối đa 160 ký tự.")
    private String dimensions;

    private boolean customizable;

    private boolean featured;

    public Long getCategoryId() { return categoryId; }
    public void setCategoryId(Long categoryId) { this.categoryId = categoryId; }
    public String getName() { return name; }
    public void setName(String name) { this.name = name; }
    public long getUnitPrice() { return unitPrice; }
    public void setUnitPrice(long unitPrice) { this.unitPrice = unitPrice; }
    public int getStockQuantity() { return stockQuantity; }
    public void setStockQuantity(int stockQuantity) { this.stockQuantity = stockQuantity; }
    public int getDiscountPercent() { return discountPercent; }
    public void setDiscountPercent(int discountPercent) { this.discountPercent = discountPercent; }
    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }
    public String getMaterial() { return material; }
    public void setMaterial(String material) { this.material = material; }
    public String getImageUrl() { return imageUrl; }
    public void setImageUrl(String imageUrl) { this.imageUrl = imageUrl; }
    public UUID getManagedMediaId() { return managedMediaId; }
    public void setManagedMediaId(UUID managedMediaId) { this.managedMediaId = managedMediaId; }
    public String getSku() { return sku; }
    public void setSku(String sku) { this.sku = sku; }
    public boolean isSkuAutoGenerated() { return skuAutoGenerated; }
    public void setSkuAutoGenerated(boolean skuAutoGenerated) { this.skuAutoGenerated = skuAutoGenerated; }
    public String getShortDescription() { return shortDescription; }
    public void setShortDescription(String shortDescription) { this.shortDescription = shortDescription; }
    public String getCustomizationGuide() { return customizationGuide; }
    public void setCustomizationGuide(String customizationGuide) { this.customizationGuide = customizationGuide; }
    public BigDecimal getCompareAtPrice() { return compareAtPrice; }
    public void setCompareAtPrice(BigDecimal compareAtPrice) { this.compareAtPrice = compareAtPrice; }
    public int getMinOrderQuantity() { return minOrderQuantity; }
    public void setMinOrderQuantity(int minOrderQuantity) { this.minOrderQuantity = minOrderQuantity; }
    public Integer getWeightGrams() { return weightGrams; }
    public void setWeightGrams(Integer weightGrams) { this.weightGrams = weightGrams; }
    public String getDimensions() { return dimensions; }
    public void setDimensions(String dimensions) { this.dimensions = dimensions; }
    public boolean isCustomizable() { return customizable; }
    public void setCustomizable(boolean customizable) { this.customizable = customizable; }
    public boolean isFeatured() { return featured; }
    public void setFeatured(boolean featured) { this.featured = featured; }
}
